import { describe, it, expect } from 'vitest';
import {
  automationToFlowGraph,
  hasComplexBranches,
  validateFlowGraph,
} from './flowGraph';
import { keywordMatches } from './keywordMatch';
import type { FlowGraph } from '@/lib/types';

describe('Four-Step Wizard & UX Architecture Verification', () => {
  describe('hasComplexBranches', () => {
    it('returns false for null, undefined, or empty graph', () => {
      expect(hasComplexBranches(null)).toBe(false);
      expect(hasComplexBranches(undefined)).toBe(false);
      expect(hasComplexBranches({ version: 1, nodes: [], edges: [] })).toBe(false);
    });

    it('returns false for a standard linear flow graph generated by automationToFlowGraph', () => {
      const flowData = {
        name: 'Standard Funnel',
        type: 'comment-dm',
        postId: 'all',
        keywords: ['LINK'],
        keywordsAnyMode: false,
        dmOpeningMessage: 'Hey there! Here is the link:',
        dmOpeningMessageButtonTitle: 'Get Link',
        dmResponses: [
          {
            id: 'resp_1',
            type: 'text' as const,
            content: 'Hey there!',
            buttons: [{ id: 'btn_1', title: 'Get Link', link: 'https://example.com' }],
          },
        ],
        askToFollowEnabled: true,
        followUpEnabled: true,
        followUpDelayMinutes: 60,
        followUpMessage: 'Did you check the link?',
      };

      const graph = automationToFlowGraph(flowData);
      expect(hasComplexBranches(graph)).toBe(false);

      const validation = validateFlowGraph(graph);
      expect(validation.valid).toBe(true);
      expect(validation.errors).toHaveLength(0);
    });

    it('returns true when custom node IDs exist (e.g. from visual builder canvas)', () => {
      const graph: FlowGraph = {
        version: 1,
        nodes: [
          { id: 'node_trigger', type: 'trigger', position: { x: 0, y: 0 }, data: { label: 'T' } },
          { id: 'node_dm_1', type: 'send_dm', position: { x: 0, y: 100 }, data: { label: 'DM', messageText: 'Hi' } },
          { id: 'custom_branch_node_1', type: 'send_dm', position: { x: 200, y: 100 }, data: { label: 'Custom', messageText: 'Branch' } },
        ],
        edges: [
          { id: 'e1', source: 'node_trigger', target: 'node_dm_1' },
          { id: 'e2', source: 'node_trigger', target: 'custom_branch_node_1' },
        ],
      };

      expect(hasComplexBranches(graph)).toBe(true);
    });

    it('returns true when multiple edges leave a single node', () => {
      const graph: FlowGraph = {
        version: 1,
        nodes: [
          { id: 'node_trigger', type: 'trigger', position: { x: 0, y: 0 }, data: { label: 'T' } },
          { id: 'node_dm_1', type: 'send_dm', position: { x: 0, y: 100 }, data: { label: 'DM', messageText: 'Hi' } },
          { id: 'node_delay', type: 'delay', position: { x: 100, y: 100 }, data: { label: 'Delay', delayMinutes: 30 } },
        ],
        edges: [
          { id: 'e1', source: 'node_trigger', target: 'node_dm_1' },
          { id: 'e2', source: 'node_trigger', target: 'node_delay' },
        ],
      };

      expect(hasComplexBranches(graph)).toBe(true);
    });

    it('returns true if multiple condition or send_dm nodes exist', () => {
      const graph: FlowGraph = {
        version: 1,
        nodes: [
          { id: 'node_trigger', type: 'trigger', position: { x: 0, y: 0 }, data: { label: 'T' } },
          { id: 'node_dm_1', type: 'send_dm', position: { x: 0, y: 100 }, data: { label: 'DM 1', messageText: 'Hi' } },
          { id: 'node_dm_2', type: 'send_dm', position: { x: 0, y: 200 }, data: { label: 'DM 2', messageText: 'Hi 2' } },
        ],
        edges: [
          { id: 'e1', source: 'node_trigger', target: 'node_dm_1' },
          { id: 'e2', source: 'node_dm_1', target: 'node_dm_2' },
        ],
      };

      expect(hasComplexBranches(graph)).toBe(true);
    });
  });

  describe('Step 2 Excluded Keywords Logic', () => {
    it('matches included keywords when excluded keywords are not triggered', () => {
      const text = 'Hey can you send me the LINK please?';
      const included = ['LINK', 'GUIDE'];
      const excluded = ['SCAM', 'FAKE', 'HATE'];

      expect(keywordMatches(text, included)).toBe(true);
      expect(keywordMatches(text, excluded)).toBe(false);
    });

    it('detects when excluded keywords are present', () => {
      const spamComment = 'This is a complete SCAM do not click';
      const excluded = ['SCAM', 'FAKE', 'HATE'];

      expect(keywordMatches(spamComment, excluded)).toBe(true);
    });

    it('handles uppercase and lowercase variations in excluded keywords', () => {
      const comment1 = 'Looks fake to me';
      const comment2 = 'WARNING: FAKE account';
      const excluded = ['FAKE'];

      expect(keywordMatches(comment1, excluded)).toBe(true);
      expect(keywordMatches(comment2, excluded)).toBe(true);
    });
  });

  describe('Step 1-4 End-to-End Canonical Graph Compilation', () => {
    it('compiles Step 1-3 form state into a valid canonical FlowGraph', () => {
      const wizardData = {
        name: 'VIP Guide Giveaway',
        type: 'comment-dm',
        postId: 'all',
        keywords: ['VIP', 'GUIDE'],
        keywordsAnyMode: false,
        excludedKeywords: ['SPAM'],
        dmOpeningMessage: 'Hey {username}! Here is your VIP guide access: 👇',
        dmResponses: [
          {
            id: 'resp_1',
            type: 'text' as const,
            content: 'Hey {username}! Here is your VIP guide access: 👇',
            buttons: [
              { id: 'btn_1', title: 'Download Guide', link: 'https://example.com/guide.pdf' },
              { id: 'btn_2', title: 'Join Community', link: 'https://example.com/community' },
            ],
          },
        ],
        askToFollowEnabled: false,
        followUpEnabled: true,
        followUpDelayMinutes: 180,
        followUpMessage: 'Hey {username}, did you download the VIP guide yet?',
      };

      const compiledGraph = automationToFlowGraph(wizardData);

      expect(compiledGraph.version).toBe(1);
      expect(compiledGraph.nodes.length).toBeGreaterThanOrEqual(4);

      // Verify trigger node
      const trigger = compiledGraph.nodes.find((n) => n.type === 'trigger');
      expect(trigger).toBeDefined();
      expect(trigger?.data.keywords).toEqual(['VIP', 'GUIDE']);
      expect(trigger?.data.keywordsAnyMode).toBe(false);

      // Verify DM node
      const dm = compiledGraph.nodes.find((n) => n.type === 'send_dm');
      expect(dm).toBeDefined();
      expect(dm?.data.messageText).toContain('{username}');
      expect(dm?.data.buttons).toHaveLength(2);
      expect(dm?.data.buttons?.[0]?.title).toBe('Download Guide');

      // Verify delay and follow-up nodes
      const delay = compiledGraph.nodes.find((n) => n.type === 'delay');
      expect(delay?.data.delayMinutes).toBe(180);

      const followUp = compiledGraph.nodes.find((n) => n.type === 'follow_up');
      expect(followUp?.data.followUpText).toContain('did you download');

      // Verify graph validation passes
      const validation = validateFlowGraph(compiledGraph);
      expect(validation.valid).toBe(true);
      expect(validation.errors).toHaveLength(0);
    });

    it('properly compiles Any Comment mode to wildcard in FlowGraph', () => {
      const anyCommentData = {
        name: 'Broad Giveaway',
        type: 'comment-dm',
        postId: 'all',
        keywords: [],
        keywordsAnyMode: true,
        dmOpeningMessage: 'Welcome! Enjoy the giveaway.',
        dmResponses: [],
      };

      const graph = automationToFlowGraph(anyCommentData);
      const trigger = graph.nodes.find((n) => n.type === 'trigger');
      expect(trigger?.data.keywordsAnyMode).toBe(true);
      expect(trigger?.data.keywords).toEqual([]);

      const validation = validateFlowGraph(graph);
      expect(validation.valid).toBe(true);
    });

    it('properly compiles Shared Reel DM trigger into FlowGraph', () => {
      const reelData = {
        name: 'Shared Reel Welcome',
        type: 'reel-dm',
        postId: null,
        keywords: [],
        keywordsAnyMode: true,
        dmOpeningMessage: 'Thanks for sending this Reel! Here are the details:',
        dmResponses: [],
      };

      const graph = automationToFlowGraph(reelData);
      const trigger = graph.nodes.find((n) => n.type === 'trigger');
      expect(trigger?.data.triggerType).toBe('reel_dm');
      expect(trigger?.data.reelMatchAny).toBe(true);

      const validation = validateFlowGraph(graph);
      expect(validation.valid).toBe(true);
    });
  });

  describe('Section 1 & 4: Name Limits & Legacy Automation Compatibility', () => {
    it('supports automation names up to 200 characters without truncation', () => {
      const longName = 'A'.repeat(200);
      expect(longName.length).toBe(200);

      const flowData = {
        name: longName,
        type: 'comment-dm',
        postId: 'all',
        keywords: ['VIP'],
        keywordsAnyMode: false,
        dmOpeningMessage: 'Hello!',
        dmResponses: [],
      };

      const graph = automationToFlowGraph(flowData);
      expect(graph.nodes.length).toBeGreaterThanOrEqual(3);
      expect(validateFlowGraph(graph).valid).toBe(true);
    });

    it('preserves custom nodes and branching edges when editing a legacy complex FlowGraph', () => {
      // Legacy automation with a custom branch (condition -> custom_dm_vip)
      const legacyGraph: FlowGraph = {
        version: 1,
        nodes: [
          { id: 'node_trigger', type: 'trigger', position: { x: 0, y: 0 }, data: { label: 'Trigger', keywords: ['OLD'] } },
          { id: 'node_dm_1', type: 'send_dm', position: { x: 0, y: 150 }, data: { label: 'DM 1', messageText: 'Old DM' } },
          { id: 'custom_cond_vip', type: 'condition', position: { x: 0, y: 300 }, data: { label: 'VIP Check', conditionType: 'is_following' } },
          { id: 'custom_dm_vip', type: 'send_dm', position: { x: 250, y: 450 }, data: { label: 'Exclusive VIP Offer', messageText: 'VIP only link' } },
          { id: 'node_end', type: 'end', position: { x: 0, y: 600 }, data: { label: 'End' } },
        ],
        edges: [
          { id: 'e1', source: 'node_trigger', target: 'node_dm_1' },
          { id: 'e2', source: 'node_dm_1', target: 'custom_cond_vip' },
          { id: 'e3', source: 'custom_cond_vip', target: 'custom_dm_vip', sourceHandle: 'yes' },
          { id: 'e4', source: 'custom_cond_vip', target: 'node_end', sourceHandle: 'no' },
          { id: 'e5', source: 'custom_dm_vip', target: 'node_end' },
        ],
      };

      expect(hasComplexBranches(legacyGraph)).toBe(true);

      // Creator edits the automation in the 4-step wizard
      const editedFlowData = {
        name: 'Updated Legacy Funnel',
        type: 'comment-dm',
        postId: 'all',
        keywords: ['NEW_KEYWORD'],
        keywordsAnyMode: false,
        dmOpeningMessage: 'Updated Opening Message for 2026! ✨',
        flowGraph: legacyGraph,
      };

      const syncedGraph = automationToFlowGraph(editedFlowData);

      // Verify custom nodes and all 5 edges are completely preserved
      expect(hasComplexBranches(syncedGraph)).toBe(true);
      expect(syncedGraph.nodes).toHaveLength(5);
      expect(syncedGraph.edges).toHaveLength(5);

      const customDm = syncedGraph.nodes.find((n) => n.id === 'custom_dm_vip');
      expect(customDm).toBeDefined();
      expect(customDm?.data.messageText).toBe('VIP only link');

      const customCond = syncedGraph.nodes.find((n) => n.id === 'custom_cond_vip');
      expect(customCond).toBeDefined();

      // Verify primary nodes were synced with new edits
      const updatedTrigger = syncedGraph.nodes.find((n) => n.id === 'node_trigger');
      expect(updatedTrigger?.data.keywords).toEqual(['NEW_KEYWORD']);

      const updatedDm = syncedGraph.nodes.find((n) => n.id === 'node_dm_1');
      expect(updatedDm?.data.messageText).toBe('Updated Opening Message for 2026! ✨');
    });

    it('preserves all linear settings (variants, excluded keywords, delay, buttons) across save and reload', () => {
      const original = {
        name: 'Full Linear Automation',
        type: 'comment-dm',
        postId: 'post_123',
        postThumbnailUrl: 'https://example.com/thumb.jpg',
        postCaption: 'Great post caption',
        keywords: ['GUIDE'],
        keywordsAnyMode: false,
        excludedKeywords: ['SPAM', 'BOT'],
        dmOpeningMessage: 'Hey {username}! Here is your guide:',
        dmOpeningMessageVariations: [
          'Hey {username}! Here is your guide:',
          'Hi {username}! Super glad to share this:',
        ],
        dmOpeningMessageButtonTitle: 'Get Guide',
        dmResponses: [
          {
            id: 'resp_1',
            type: 'text' as const,
            content: 'Hey {username}! Here is your guide:',
            buttons: [
              { id: 'btn_1', title: 'Get Guide', link: 'https://example.com/guide' },
              { id: 'btn_2', title: 'Bonus Checklist', link: 'https://example.com/bonus' },
            ],
          },
        ],
        askToFollowEnabled: true,
        followUpEnabled: true,
        followUpDelayMinutes: 1440,
        followUpMessage: 'Did you check the guide, {username}?',
      };

      const graph = automationToFlowGraph(original);
      expect(hasComplexBranches(graph)).toBe(false);

      const triggerNode = graph.nodes.find((n) => n.type === 'trigger');
      expect(triggerNode?.data.postId).toBe('post_123');
      expect(triggerNode?.data.keywords).toEqual(['GUIDE']);

      const dmNode = graph.nodes.find((n) => n.type === 'send_dm');
      expect(dmNode?.data.buttons).toHaveLength(2);
      expect(dmNode?.data.messageVariations).toHaveLength(2);

      const delayNode = graph.nodes.find((n) => n.type === 'delay');
      expect(delayNode?.data.delayMinutes).toBe(1440);
    });

    it('manages public comment replies with template insertion, AI generation, and inline editing while preserving other settings', () => {
      const initialFlow = {
        name: 'AI Reply Comment Funnel',
        type: 'comment-dm',
        postId: 'all',
        keywords: ['VIP'],
        keywordsAnyMode: false,
        excludedKeywords: ['SCAM'],
        publicReplyEnabled: true,
        publicReplyOptions: ['Initial reply 1'],
        customReplies: ['Initial reply 1'],
        dmOpeningMessage: 'Hey {username}! Here is your VIP link:',
        dmOpeningMessageButtonTitle: 'Get Link',
        dmResponses: [{ id: '1', type: 'text' as const, content: 'VIP link' }],
        askToFollowEnabled: false,
        followUpEnabled: true,
        followUpDelayMinutes: 60,
        followUpMessage: 'Did you check the link?',
      };

      // 1. Template insertion
      const TEMPLATES = [
        "Sent you a DM! Check your requests 📥",
        "Check your inbox! Just sent it over ✨",
        "Just messaged you the link! 🚀",
        "Sent to your DMs! Let me know if you got it 📬",
        "All sent! Check your message requests 🙌",
      ];
      const withTemplates = {
        ...initialFlow,
        publicReplyOptions: [...TEMPLATES],
        customReplies: [...TEMPLATES],
      };
      expect(withTemplates.publicReplyOptions).toHaveLength(5);
      expect(withTemplates.keywords).toEqual(['VIP']);
      expect(withTemplates.excludedKeywords).toEqual(['SCAM']);

      // 2. AI generation population
      const aiGeneratedReplies = [
        "Just sent to your DMs! 📩",
        "Check your inbox! ✨",
        "All details are in your requests! 🚀",
        "Sent! Enjoy the guide 🙌",
        "Messaged you directly! 📬",
      ];
      const withAi = {
        ...withTemplates,
        publicReplyOptions: aiGeneratedReplies,
        customReplies: aiGeneratedReplies,
      };
      expect(withAi.publicReplyOptions).toHaveLength(5);
      expect(withAi.publicReplyOptions[0]).toBe("Just sent to your DMs! 📩");

      // 3. Inline editing of an AI reply
      const editedReplies = [...withAi.publicReplyOptions];
      editedReplies[0] = "Just sent to your DMs! Let me know what you think 📩";
      const withEdited = {
        ...withAi,
        publicReplyOptions: editedReplies,
        customReplies: editedReplies,
      };
      expect(withEdited.publicReplyOptions[0]).toBe("Just sent to your DMs! Let me know what you think 📩");
      expect(withEdited.publicReplyOptions[1]).toBe("Check your inbox! ✨");

      // 4. Verify all unrelated settings remain completely preserved
      expect(withEdited.name).toBe('AI Reply Comment Funnel');
      expect(withEdited.keywords).toEqual(['VIP']);
      expect(withEdited.excludedKeywords).toEqual(['SCAM']);
      expect(withEdited.dmOpeningMessage).toBe('Hey {username}! Here is your VIP link:');
      expect(withEdited.followUpDelayMinutes).toBe(60);

      // 5. Compiles cleanly into canonical flow graph with public_reply_options
      const graph = automationToFlowGraph(withEdited);
      const dmNode = graph.nodes.find((n) => n.type === 'send_dm');
      expect(dmNode?.data.publicReplyOptions).toEqual(editedReplies);
    });

    it('preserves existing public replies without corruption when AI generation fails', () => {
      const existingFlow = {
        name: 'Existing Replies Funnel',
        type: 'comment-dm',
        postId: 'all',
        keywords: ['HELP'],
        keywordsAnyMode: false,
        publicReplyEnabled: true,
        publicReplyOptions: ['My custom reply 1', 'My custom reply 2'],
        customReplies: ['My custom reply 1', 'My custom reply 2'],
        dmOpeningMessage: 'Hey {username}!',
        dmOpeningMessageButtonTitle: 'Help',
        dmResponses: [{ id: '1', type: 'text' as const, content: 'Help' }],
        askToFollowEnabled: false,
        followUpEnabled: false,
        followUpDelayMinutes: 60,
        followUpMessage: '',
      };

      // Simulate a failure in AI generation (status: 503 fallback)
      const simulatedFailureResponse = {
        success: false,
        status: 'fallback',
        error: 'AI generation is currently unavailable.',
      };

      // Handler logic: on failure, onUpdate is NOT called with new replies
      let updatedFlow = { ...existingFlow };
      let aiError: string | null = null;

      if (!simulatedFailureResponse.success || simulatedFailureResponse.status === 'fallback') {
        aiError = simulatedFailureResponse.error;
      } else {
        updatedFlow = {
          ...updatedFlow,
          publicReplyOptions: (simulatedFailureResponse as any).variations,
        };
      }

      // Assert that existing replies were 100% preserved
      expect(updatedFlow.publicReplyOptions).toEqual(['My custom reply 1', 'My custom reply 2']);
      expect(aiError).toBe('AI generation is currently unavailable.');

      // Templates still work independently if user decides to use them
      const TEMPLATES = [
        "Sent you a DM! Check your requests 📥",
        "Check your inbox! Just sent it over ✨",
        "Just messaged you the link! 🚀",
        "Sent to your DMs! Let me know if you got it 📬",
        "All sent! Check your message requests 🙌",
      ];
      updatedFlow.publicReplyOptions = [...TEMPLATES];
      expect(updatedFlow.publicReplyOptions).toHaveLength(5);
    });
  });
});
